"""Cost per deflected ticket and the 10x plan, computed from the last eval run, not typed in.

    python scripts/cost_and_10x.py              # newest full run: fix1 if it exists, else after
    python scripts/cost_and_10x.py --tag after  # a named run

Measured inputs come from docs/archive/deliverables/week12/eval/results_<tag>.jsonl. Limits were measured on 2026-10-16 (see the
constants for where each came from). Assumptions are labelled ASSUMPTION; change them in one place.
"""
import argparse
import json
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
EVAL = ROOT / "docs" / "archive" / "deliverables" / "week12" / "eval"
OUT = ROOT / "docs" / "archive" / "deliverables" / "week12" / "cost_and_10x.md"

# Limits, prices and the capacity assumptions are settings and model prices in the catalog (Admin, Settings and Admin,
# Model prices), read when the script runs; the measured provider limits were entered there on 2026-10-16.
from src.catalog import eval_store, prices, settings  # noqa: E402

LIMIT_TPM = settings.get("provider.tpm")
LIMIT_RPD = settings.get("provider.rpd")
LIMIT_TPD = settings.get("provider.tpd")
_price = prices.for_model(settings.get("models.agent"))
PRICE_IN, PRICE_OUT = _price["input_per_1m"], _price["output_per_1m"]
TICKETS_PER_MONTH = settings.get("capacity.tickets_per_month")
BLACK_FRIDAY_WEEK = settings.get("capacity.black_friday_week")
PEAK_HOUR_SHARE = settings.get("capacity.peak_hour_share")
DAYS_PER_MONTH = 30


def fmt(n: float, digits: int = 0) -> str:
    return f"{n:,.{digits}f}"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tag", default="fix1" if eval_store.run("fix1") else "after")
    tag = ap.parse_args(argv).tag
    rows = eval_store.results(tag)
    summary = eval_store.run(tag)["summary"]
    cl = summary["cost_latency"]
    # latency must come from a run whose model calls were NOT mostly served from the cache
    cache = summary.get("llm_cache") or {}
    calls = cache.get("hits", 0) + cache.get("misses", 0)
    latency_note = f"the `{tag}` run"
    if calls and cache.get("hits"):
        latency_note += (f"; {cache['hits']} of {calls} model calls were served from the response cache, which flatters the median. "
                         "Uncached tickets that arrive back to back wait about a minute for the per-minute limit")
    if calls and cache.get("hits", 0) / calls > 0.25:
        uncached = eval_store.run("after_run1_judge_without_order_facts")["summary"]["cost_latency"]
        cl = {**cl, "p50_latency_s": uncached["p50_latency_s"], "p95_latency_s": uncached["p95_latency_s"]}
        latency_note = "the uncached first run (the chosen run was mostly served from the response cache)"
    prefetch_on = "prefetch" not in (summary.get("ablate") or "") and tag not in ("after", "before") and not tag.startswith("after_")

    mix = [r for r in rows if r["slice"] == "random"]            # closest thing to a real ticket mix
    model_rows = [r for r in mix if r["total_tokens"] > 0]
    model_share = len(model_rows) / len(mix)
    tokens = statistics.mean(r["total_tokens"] for r in model_rows)
    laps = statistics.mean(r["laps"] for r in model_rows)
    cost_model = statistics.mean(r["cost_usd"] for r in model_rows)

    scenarios = [
        ("Today (2,000 per month)", TICKETS_PER_MONTH / DAYS_PER_MONTH),
        ("10x (20,000 per month)", TICKETS_PER_MONTH * 10 / DAYS_PER_MONTH),
        ("Black Friday week (20,000 in 7 days)", BLACK_FRIDAY_WEEK / 7),
    ]
    cap_tpd = LIMIT_TPD / (tokens * model_share)
    cap_rpd = LIMIT_RPD / (laps * model_share)
    cap_tpm = LIMIT_TPM / (PEAK_HOUR_SHARE / 60 * model_share * tokens)
    today = TICKETS_PER_MONTH / DAYS_PER_MONTH

    lines = [
        "# Cost per deflected ticket and the 10x plan", "",
        f"Generated by `scripts/cost_and_10x.py` from the eval run `{tag}` ({summary['n']} cases"
        + (", entitlement check and first search prefetched in code" if prefetch_on else "") + "). Corpus and tickets are synthetic.", "",
        "## Cost per deflected ticket", "",
        f"- Total model spend across the {summary['n']}-case run: **${cl['total_cost_usd']}** (agent plus guards; the judge is eval-only and excluded)",
        f"- Deflected tickets (answered and every assertion passed): **{cl['deflected_assertions_only']}**",
        f"- **Cost per deflected ticket: ${cl['cost_per_deflected_usd']}**. This divides ALL spend, including tickets that escalated, by deflected tickets only, "
        "so escalations are charged to the ones that succeeded.",
        f"- A ticket that reaches the model costs about ${cost_model:.5f} ({fmt(tokens)} tokens over {laps:.1f} model calls on average).",
        f"- {100 * (1 - model_share):.0f}% of the random sample never reaches a model (the pre-guard escalates legal, safety, fraud and injection text for free).",
        f"- Prices used: ${PRICE_IN} in and ${PRICE_OUT} out per million tokens for {settings.get('models.agent')}, from the catalog's model prices "
        f"({_price.get('source') or 'source not recorded'}, checked {_price.get('checked_on') or 'date not recorded'}). Free-tier usage is not billed; these are the paid on-demand rates.", "",
        "## What breaks first at volume", "",
        "Three provider limits apply to this model on the free tier. Two come from response headers; the third is **not in any header** and was found the hard way:",
        f"after a day of testing, requests started failing with `tokens per day (TPD): Limit {fmt(LIMIT_TPD)}, Used 199,313`.", "",
        f"| Limit | Value | Source |", "|---|---|---|",
        f"| Tokens per minute | {fmt(LIMIT_TPM)} | response header |",
        f"| Requests per day | {fmt(LIMIT_RPD)} | response header |",
        f"| **Tokens per day** | **{fmt(LIMIT_TPD)}** | error body of a 429 on 2026-10-16 |", "",
        f"Per ticket that reaches a model: {fmt(tokens)} tokens and {laps:.1f} requests. Model-ticket share: {100 * model_share:.0f}% (random sample, n={len(mix)}).",
        f"ASSUMPTION: {int(PEAK_HOUR_SHARE * 100)}% of a day's tickets arrive in the busiest hour.", "",
        "| Scenario | Tickets/day | Tokens/day (limit " + fmt(LIMIT_TPD) + ") | Requests/day (limit " + fmt(LIMIT_RPD) + ") | Peak tokens/min (limit " + fmt(LIMIT_TPM) + ") | Monthly spend | First to break |",
        "|---|---|---|---|---|---|---|",
    ]
    for name, per_day in scenarios:
        model_per_day = per_day * model_share
        tpd, rpd = model_per_day * tokens, model_per_day * laps
        peak_tpm = per_day * PEAK_HOUR_SHARE / 60 * model_share * tokens
        monthly = per_day * DAYS_PER_MONTH * model_share * cost_model
        utils = {"tokens per day": tpd / LIMIT_TPD, "requests per day": rpd / LIMIT_RPD, "tokens per minute": peak_tpm / LIMIT_TPM}
        worst = max(utils, key=utils.get)
        first = "nothing yet" if utils[worst] < 1 else f"{worst} ({utils[worst]:.1f}x over)"
        lines.append(f"| {name} | {fmt(per_day)} | {fmt(tpd)} ({100 * utils['tokens per day']:.0f}%) | {fmt(rpd)} ({100 * utils['requests per day']:.0f}%) | "
                     f"{fmt(peak_tpm)} ({100 * utils['tokens per minute']:.0f}%) | ${monthly:.2f} | {first} |")

    lines += [
        "", f"**Answer: the daily token limit breaks first, and it is already below today's volume.** It caps the system at about "
        f"**{fmt(cap_tpd)} tickets a day** ({fmt(cap_tpd * DAYS_PER_MONTH)} a month), against {fmt(today)} a day today. "
        f"The daily request limit would allow about {fmt(cap_rpd)} a day and the per-minute limit about {fmt(cap_tpm)} a day at peak, "
        "so those matter only after the token limit is lifted. Money is not the problem: spend stays in single dollars at every scenario above.", "",
        f"This is not hypothetical. This {summary['n']}-case evaluation run used {fmt(sum(r['total_tokens'] for r in rows))} agent tokens "
        "(the judges run on a different model with its own limit). On 2026-10-16 one run plus a few experiments exhausted the "
        "day's allowance and a later run failed halfway; the evaluation now stops, keeps the finished cases and continues with "
        "`--resume` instead of recording the failures as if they were the system's (`seams.md` 44).", "",
        f"Steady-state speed: at {fmt(tokens)} tokens per model ticket (random sample; the whole 39-case suite averages "
        f"{cl['mean_tokens_per_llm_ticket']} because many of its cases are short) the per-minute limit allows "
        f"**{LIMIT_TPM / tokens:.2f} tickets per minute**, which is why back-to-back tickets queue behind the limiter "
        f"(p50 latency {cl['p50_latency_s']} s, p95 {cl['p95_latency_s']} s, from {latency_note}).", "",
        "## What to do about it, ranked by impact", "",
        "| # | Change | Effect | Cost and risk |",
        "|---|---|---|---|",
        "| 1 | Move off the free tier (the provider's error message points to its paid Dev Tier) | Lifts all three limits. The paid limits are NOT measured here, so size them before promising a number | Money; check the price table in `src/generation/cost.py` first |",
        (f"| 2 | DONE in this run: the entitlement check and first search run in code before lap 1 (prefetch), and the model keeps every "
         f"tool for anything else | Measured here: {fmt(tokens)} tokens and {laps:.1f} model calls per model ticket. Compare the `after` run "
         "(no prefetch) and `docs/archive/deliverables/week12/eval/report_pf10_*.md` for a 10-ticket A/B | The model no longer chooses those two calls, so "
         "the report measures tool choice on the calls it still makes |" if prefetch_on else
         f"| 2 | Run the two tool calls that always happen (entitlement, search) in CODE before the model (prefetch) | "
         f"Fewer requests and tokens per ticket; measure with `python -m tier1 eval --ablate prefetch` against a normal run | "
         "The model no longer chooses those two calls |"),
        "| 3 | Shorter system prompt and search snippets cut from 700 to about 400 characters | Fewer tokens per ticket | Quality risk: re-run the eval |",
        "| 4 | Queue tickets with a small worker pool and show 'working' in the UI | A burst becomes waiting instead of failures. Does NOT raise the daily token cap | A day of work; a real queue (Redis or similar) once there is more than one process |",
        "| 5 | Cache answers to repeated questions | Unknown share of repeats in real traffic: not measured | Staleness: must be invalidated when a policy document changes |", "",
        "Not measured: real concurrency behaviour, paid-tier limits, provider-side prompt caching and the real share of repeated questions.",
    ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines[14:40]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
